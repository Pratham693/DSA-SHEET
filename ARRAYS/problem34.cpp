#include <iostream>
#include <bits/stdc++.h>
using namespace std;
// Problem -> Two Sum
// Brute Force
// Time Complixty -> O(n^3 + nlog(n)) & Space Complixty -> O(n^2)
vector<vector<int>> triplet(int arr[], int n)
{
    set<vector<int>> st;
    for (int i = 0; i < n; i++)
    {
        for (int j = i + 1; j < n; j++)
        {
            for (int k = j + 1; k < n; k++)
            {
                if ((arr[i] + arr[j] + arr[k]) == 0)
                {
                    vector<int> temp = {arr[i], arr[j], arr[k]};
                    sort(temp.begin(), temp.end());
                    st.insert(temp);
                }
            }
        }
    }
    vector<vector<int>> ans(st.begin(), st.end());
    return ans;
}
// Better Version
// Time Complexity ->O(n^2  * log(n)) & Space Complexity -> O(n log M)
vector<vector<int>> triplet2(int arr[], int n)
{
    set<vector<int>> st;
    for (int i = 0; i < n; i++)
    {
        set<int> hashset;
        for (int j = i + 1; j < n; j++)
        {
            int third = -(arr[i] + arr[j]);
            if (hashset.find(third) != hashset.end())
            {
                vector<int> temp = {arr[i], arr[j], third};
                sort(temp.begin(), temp.end());
                st.insert(temp);
            }
            hashset.insert(arr[j]);
        }
    }
    vector<vector<int>> ans(st.begin(), st.end());
    return ans;
}


int main()
{
    int arr[] = {-1, 0, 1, 1, -1, -4};
    vector<vector<int>> ans = triplet2(arr, 7);

    for (int i = 0; i < ans.size(); i++)
    {
        for (int j = 0; j < ans[i].size(); j++)
        {
            cout << ans[i][j] << ", ";
        }
        cout << endl;
    }

    return 0;
}